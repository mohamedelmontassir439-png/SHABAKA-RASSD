def get_lang(req: Request) -> str:
    q = req.query_params.get("lang")
    if q in SUPPORTED_LANGS:
        return q
    c = req.cookies.get("lang")
    if c in SUPPORTED_LANGS:
        return c
    return DEFAULT_LANG


def tr(key: str, lang: str = DEFAULT_LANG, **kwargs) -> str:
    """Traduction directe depuis du code Python (routes, validators) —
    contrepartie de make_t() qui sert côté templates Jinja."""
    entry = T.get(key)
    if not entry:
        return key
    text = entry.get(lang, entry.get(DEFAULT_LANG, key))
    if kwargs:
        try:
            text = text.format(**kwargs)
        except (KeyError, IndexError):
            pass
    return text


def make_t(lang: str):
    def t(key: str, **kwargs) -> str:
        return tr(key, lang, **kwargs)
    return t
